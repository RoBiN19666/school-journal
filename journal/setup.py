"""Первоначальная настройка журнала: что считать «первым запуском».

Пока в рабочей базе нет ни одного активного администратора, журнал считается
ненастроенным: ``FirstRunSetupMiddleware`` уводит все страницы на ``/setup/``,
где создаётся первая учётная запись и задаётся внешний вид. Как только
администратор появился, журнал работает как обычно — никаких редиректов.

Администратором считается и главный администратор, и администратор, и
суперпользователь Django: владельца журнала могли создать штатной формой
«Сотрудники УМО» с ролью «администратор», и мастер ему не нужен. Мастер
появляется только на пустой базе или там, где есть лишь преподаватели
и методисты.

Здесь же живёт список адресов, которые доступны до настройки: сама страница
настройки, переключатель языка, статика, загруженные знаки, проверка
работоспособности, демонстрация и админка Django.
"""
import logging

from django.db import DatabaseError

logger = logging.getLogger(__name__)

#: Имя маршрута страницы настройки (объявлено в journal/urls.py).
SETUP_URL_NAME = "setup"

#: Адрес страницы настройки: на него ведёт мастер первого запуска.
SETUP_PATH = "/setup/"

#: Адреса, доступные до первоначальной настройки. Мастер не должен закрывать
#: собой то, чем журнал пользуется до появления первой учётной записи: статику,
#: загруженные знаки, демонстрацию, проверку работоспособности и админку.
SETUP_EXEMPT_PREFIXES = (
    SETUP_PATH,
    # Штатный переключатель языка (POST /i18n/setlang/): без него мастер
    # первого запуска не может сменить язык, потому что middleware уводит
    # запрос на /setup/ раньше, чем Django успевает поставить cookie.
    "/i18n/",
    "/static/",
    "/media/",
    "/healthcheck",
    "/demo/",
    "/admin/",
    "/favicon.ico",
)

#: Те же адреса без косой черты на конце: Django сам перенаправит на «/demo/»,
#: «/admin/» или «/setup/», а не на страницу настройки.
SETUP_EXEMPT_EXACT = ("/setup", "/demo", "/admin", "/healthcheck")

#: Служебные файлы (скрипты, картинки, шрифты) отдаются всегда.
SETUP_EXEMPT_SUFFIXES = (
    ".css",
    ".js",
    ".png",
    ".jpg",
    ".jpeg",
    ".ico",
    ".svg",
    ".webp",
    ".woff",
    ".woff2",
    ".map",
)


def is_setup_exempt(path):
    """Доступен ли адрес до первоначальной настройки (редиректа не будет)."""
    path = path or ""
    if path in SETUP_EXEMPT_EXACT:
        return True
    if path.startswith(SETUP_EXEMPT_PREFIXES):
        return True
    return path.endswith(SETUP_EXEMPT_SUFFIXES)


#: Роли, которые означают, что журнал уже настроен: главный администратор и
#: администратор (та же пара ролей, что в forms.ADMIN_ROLE_VALUES).
ADMIN_ROLE_VALUES = ("superadmin", "admin")


def admins_exist():
    """Есть ли в базе хотя бы один активный администратор журнала.

    Считаем администратором главного администратора, администратора и
    суперпользователя Django. Отключённые учётные записи не в счёт: журнал,
    где остались только преподаватели и методисты, настраивать ещё нужно.
    """
    from django.db.models import Q

    from .models import User

    return (
        User.objects.filter(is_active=True)
        .filter(Q(role__in=ADMIN_ROLE_VALUES) | Q(is_superuser=True))
        .exists()
    )


def setup_required():
    """Нужна ли первоначальная настройка: администратора в журнале ещё нет.

    Если база не готова (таблиц ещё нет, нет соединения), настройку не требуем:
    пусть страница покажет свою ошибку, а не молчаливый редирект на мастер.
    """
    try:
        return not admins_exist()
    except DatabaseError as error:
        logger.warning("Не удалось проверить администраторов журнала: %s", error)
        return False
